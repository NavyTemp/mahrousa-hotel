const DICTS: Record<Lang, Record<string, string>> = {
  en: {},
  ar: AR,
};

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const base = lang === "en" ? key : DICTS[lang][key] ?? key;
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (_, k) =>
    k in vars ? String(vars[k]) : `{${k}}`,
  );
}
